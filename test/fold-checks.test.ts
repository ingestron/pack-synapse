// checks.sql when building every environment together (spec/behaviour.md, sections 3, 8 and
// "Quality and cleansing"): one file, with the variables views.sql has, and a checks wrapper
// per environment.
import { memoryFiles } from "@ingestron/config";
import { checkFold, resolveDefinitions, type ResolvedModel } from "@ingestron/definitions";
import { describe, expect, it } from "vitest";
import { synapse } from "../src/index.js";
import { sqlcmdFold } from "./fold-helpers.js";
import { crmFiles } from "./quality-project.js";
import { landing, tables } from "./stub-packs.js";

const models = Object.fromEntries(
  ["dev", "prod"].map((environment) => [
    environment,
    resolveDefinitions(memoryFiles(crmFiles()), {
      packs: [landing, synapse, tables],
      environment,
      deployTime: true,
      environmentsTogether: true,
    }).model as ResolvedModel,
  ]),
);

describe("checks.sql for every environment", () => {
  const built = synapse.buildEnvironments!(models);

  it("is one file with the views' variables, and a checks wrapper per environment", () => {
    expect(built.problems).toEqual([]);
    expect(Object.keys(built.files).sort()).toEqual([
      "checks.sql",
      "checks/dev.sql",
      "checks/prod.sql",
      "environments/dev.sql",
      "environments/prod.sql",
      "views.sql",
    ]);
    expect(built.files["checks.sql"]).toContain("\n\nUSE [$(database)];\n\n");
    expect(built.files["checks.sql"]).not.toContain("\nGO");
  });

  it("wraps checks.sql as views.sql is wrapped, then ends its batch", () => {
    expect(built.files["checks/prod.sql"]).toBe(
      [
        "-- Generated by Ingestron for crm: what checks.sql takes in prod. Do not edit.",
        "-- Run it from the folder that holds checks.sql: sqlcmd reads :r paths from where it starts.",
        "--   sqlcmd -S <workspace>-ondemand.sql.azuresynapse.net -i checks/prod.sql",
        ":on error exit",
        ':setvar database "crm_prod"',
        ":r checks.sql",
        "GO",
        "",
      ].join("\n"),
    );
  });

  it("holds the fold property: sqlcmd runs each environment's own checks.sql", () => {
    expect(checkFold(synapse, models, sqlcmdFold({}))).toEqual([]);
  });
});
