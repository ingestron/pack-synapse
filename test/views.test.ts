// views.sql: views over landed files, transforms as views, and views over tables other packs store.
import { describe, expect, it } from "vitest";
import { base, generate, problems, views } from "./project.js";

const flowWith = (settings: string) =>
  base["flow.yaml"]!.replace("source: erp\n", `source: erp\ningest: { with: { ${settings} } }\n`);
const transform = [
  "apiVersion: ingestron.io/v1",
  "kind: Transform",
  "id: daily",
  "inputs: [orders]",
  'code: "SELECT id, SUM(total) AS total FROM {{ tables.orders }} GROUP BY id"',
  "contract: orders",
  "",
].join("\n");
const daily = (orders: string) =>
  orders.replace(
    "  - name: orders\n",
    "  - name: daily\n    logicalType: object\n    properties:\n      - { name: id, logicalType: integer }\n      - { name: total, logicalType: number }\n  - name: orders\n",
  );

describe("views over landed files", () => {
  it("views each table's files through the data source, typed by the contract", () => {
    const sql = views();
    expect(sql).toMatch(
      /^-- Generated by Ingestron for erp \(dev\): Synapse serverless SQL views\.\n/,
    );
    expect(sql).toContain(
      [
        "IF SCHEMA_ID(N'bronze') IS NULL EXEC(N'CREATE SCHEMA [bronze]');",
        "GO",
        "CREATE OR ALTER VIEW [bronze].[orders] AS",
        "SELECT *",
        "FROM OPENROWSET(",
        "  BULK 'erp/orders/orders.parquet',",
        "  DATA_SOURCE = 'landing',",
        "  FORMAT = 'PARQUET'",
        ") WITH (",
        "  [id] BIGINT,",
        "  [total] FLOAT",
        ") AS [rows];",
        "GO",
      ].join("\n"),
    );
  });

  it("reads every file when each load adds files", () => {
    const location = "abfss://landing@acct.dfs.core.windows.net/erp/orders/*.parquet";
    expect(views({ "flow.yaml": flowWith(`location: "${location}"`) })).toContain(
      "  BULK 'erp/orders/*.parquet',",
    );
  });

  it("reads CSV files with a header row", () => {
    const location = "abfss://landing@acct.dfs.core.windows.net/erp/orders/*.csv";
    const sql = views({ "flow.yaml": flowWith(`location: "${location}", format: csv`) });
    expect(sql).toContain("  FORMAT = 'CSV',\n  PARSER_VERSION = '2.0',\n  HEADER_ROW = TRUE,");
  });

  it("refuses files outside the data source", () => {
    const location = "abfss://other@acct.dfs.core.windows.net/x.parquet";
    expect(problems({ "flow.yaml": flowWith(`location: "${location}"`) })).toEqual([
      {
        code: "METHOD_CHECK",
        message: `"synapse-view" for table "orders": ${location} is not under the data source landing (abfss://landing@acct.dfs.core.windows.net).`,
      },
    ]);
  });

  it("refuses files in a format it cannot read", () => {
    expect(problems({ "flow.yaml": flowWith("format: json") })).toEqual([
      {
        code: "METHOD_CHECK",
        message: '"synapse-view" for table "orders": it reads parquet and csv files, not json.',
      },
    ]);
  });
});

describe("transforms as views", () => {
  it("wraps the transform's SQL, naming its inputs' views, after them", () => {
    const sql = views({ "daily.yaml": transform, "orders.yaml": daily(base["orders.yaml"]!) });
    const view = [
      "CREATE OR ALTER VIEW [silver].[daily] AS",
      "SELECT [id], [total]",
      "FROM (",
      "SELECT id, SUM(total) AS total FROM [bronze].[orders] GROUP BY id",
      ") AS [source];",
    ].join("\n");
    expect(sql).toContain(view);
    expect(sql.indexOf("[bronze].[orders] AS")).toBeLessThan(sql.indexOf(view));
  });

  it("refuses a transform over a table with no Synapse view", () => {
    const flow = base["flow.yaml"]!.replace(
      "source: erp\n",
      "source: erp\nstore: { uses: keep }\n",
    );
    expect(
      problems({
        "flow.yaml": flow,
        "daily.yaml": transform,
        "orders.yaml": daily(base["orders.yaml"]!),
      }),
    ).toEqual([
      {
        code: "PACK_CHECK",
        message:
          'transform "daily" reads "orders", which has no Synapse view; store it with synapse-view or serve it with synapse-serve.',
      },
    ]);
  });
});

describe("views over tables other packs store", () => {
  const stored = (store: string) =>
    base["flow.yaml"]!.replace(
      "source: erp\n",
      `source: erp\nstore: { uses: ${store} }\nserve: { uses: synapse-serve }\n`,
    );

  it("views where the store pack keeps the table", () => {
    expect(views({ "flow.yaml": stored("keep") })).toContain(
      "CREATE OR ALTER VIEW [bronze].[orders] AS\nSELECT *\nFROM OPENROWSET(\n  BULK 'published/orders/*.parquet',",
    );
  });

  it("refuses to serve a table whose store does not say where it is", () => {
    expect(problems({ "flow.yaml": stored("opaque") }).map((item) => item.code)).toEqual([
      "HANDOVER",
    ]);
  });

  it("builds nothing when no table uses a Synapse method", () => {
    const flow = base["flow.yaml"]!.replace(
      "source: erp\n",
      "source: erp\nstore: { uses: keep }\n",
    );
    const { result, files } = generate({ "flow.yaml": flow });
    expect(result.diagnostics).toEqual([]);
    expect(files).toEqual({});
  });
});

const utf8 = "COLLATE Latin1_General_100_BIN2_UTF8";

describe("audit columns the landed files carry", () => {
  it("are read as text and timestamps converted, after the contract's columns", () => {
    const sql = views({ "flow.yaml": flowWith("audit: true") });
    expect(sql).toContain(
      `  [_loaded_at] VARCHAR(40) ${utf8},\n  [_run_id] VARCHAR(8000) ${utf8}\n) AS [rows]`,
    );
    expect(sql).toContain(", CONVERT(DATETIME2(7), [_loaded_at], 127) AS [_loaded_at], [_run_id]");
    expect(sql).not.toContain("SELECT *");
  });

  it("leave views without them as they were", () => {
    expect(views()).toContain("SELECT *");
  });
});
