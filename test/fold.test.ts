// One views.sql for every environment: variables only where environments differ,
// named after what they stand for, and a wrapper per environment that sets them.
import { describe, expect, it } from "vitest";
import { erpEnvironments, erpProject, fold, foldFailures, resolveAll } from "./fold-helpers.js";
import { synapse } from "../src/index.js";
import { base } from "./project.js";

const models = resolveAll(erpEnvironments(), ["dev", "test", "prod"]);
const built = fold(models);
const views = built.files["views.sql"]!;

describe("views.sql for every environment", () => {
  it("is one script and a wrapper per environment", () => {
    expect(built.problems).toEqual([]);
    expect(Object.keys(built.files)).toEqual([
      "views.sql",
      "environments/dev.sql",
      "environments/test.sql",
      "environments/prod.sql",
    ]);
    expect(built.deployValues).toEqual([]);
  });

  it("writes a variable only where the environments differ", () => {
    expect(views).toContain("USE [$(database)];\nGO");
    expect(views).toContain("  DATA_SOURCE = '$(data_source)',");
    expect(views).toContain("WHERE region = '$(value_totals)'");
    // The same in every environment: written as it is.
    expect(views).toContain("IF SCHEMA_ID(N'bronze') IS NULL EXEC(N'CREATE SCHEMA [bronze]');");
    expect(views).toContain("CREATE OR ALTER VIEW [bronze].[orders] AS");
    expect(views).toContain("  BULK 'erp/orders/orders.parquet',");
    expect(views).toContain("FROM [bronze].[orders] WHERE");
    expect(views.match(/\$\(/g)).toHaveLength(3);
  });

  it("sets every variable in each wrapper, then includes views.sql", () => {
    expect(built.files["environments/test.sql"]).toBe(
      [
        "-- Generated by Ingestron for erp: what views.sql takes in test. Do not edit.",
        "-- Run it from the folder that holds views.sql: sqlcmd reads :r paths from where it starts.",
        "--   sqlcmd -S <workspace>-ondemand.sql.azuresynapse.net -i environments/test.sql",
        ":on error exit",
        ':setvar database "erp_test"',
        ':setvar data_source "landing"',
        ':setvar value_totals "uk"',
        ":r views.sql",
        "",
      ].join("\n"),
    );
    expect(built.files["environments/dev.sql"]).toContain(':setvar data_source "landing_dev"');
    expect(built.files["environments/prod.sql"]).toContain(':setvar data_source "landing"');
  });

  it("gives the same files each time for the same definitions", () => {
    const again = fold(resolveAll(erpEnvironments(), ["dev", "test", "prod"]));
    expect(again).toEqual(built);
  });
});

describe("one environment", () => {
  it("is views.sql as that environment builds it, and a wrapper that sets nothing", () => {
    const one = resolveAll(base, ["dev"]);
    const { files, problems } = fold(one);
    expect(problems).toEqual([]);
    expect(files["views.sql"]).toBe(synapse.build(one.dev!)["views.sql"]);
    expect(files["views.sql"]).not.toContain("$(");
    expect(files["environments/dev.sql"]).toMatch(/:on error exit\n:r views\.sql\n$/);
    expect(foldFailures(one)).toEqual([]);
  });
});

describe("variable names", () => {
  it("are qualified by layer when each environment's views are in several databases", () => {
    const standard = base["standard.yaml"]!.replace(
      "store: { default: synapse-view }",
      'store: { default: synapse-view }\nnaming: { catalog: "erp_{{ environment }}_{{ layer }}" }',
    );
    const several = resolveAll(erpEnvironments({ "standard.yaml": standard }), ["dev", "prod"]);
    const sql = fold(several).files["views.sql"]!;
    expect(sql).toContain("USE [$(database_bronze)];");
    expect(sql).toContain("USE [$(database_silver)];");
    expect(sql).toContain("FROM [$(database_bronze)].[bronze].[orders] WHERE");
    expect(foldFailures(several)).toEqual([]);
  });

  it("name a schema by its layer and a view by its table", () => {
    const standard = base["standard.yaml"]!.replace(
      "store: { default: synapse-view }",
      'store: { default: synapse-view }\nnaming: { schema: "{{ layer }}_{{ environment }}", table: "{{ table }}_{{ environment }}" }',
    );
    const named = resolveAll(erpEnvironments({ "standard.yaml": standard }), ["dev", "prod"]);
    const sql = fold(named).files["views.sql"]!;
    expect(sql).toContain("CREATE OR ALTER VIEW [$(schema_bronze)].[$(view_orders)] AS");
    expect(sql).toContain("EXEC(N'CREATE SCHEMA [$(schema_bronze)]')");
    expect(sql).toContain("FROM [$(schema_bronze)].[$(view_orders)] WHERE");
    expect(foldFailures(named)).toEqual([]);
  });

  it("name a file path and a CSV delimiter by their table", () => {
    const flow = base["flow.yaml"]!.replace(
      "source: erp\n",
      "source: erp\ningest: { with: { format: csv, location: 'abfss://landing@acct.dfs.core.windows.net/${environment.name}/orders/*.csv', csv: { delimiter: '${values.delimiter}' } } }\n",
    );
    const project = erpProject(
      ["  dev: { values: { delimiter: ';' } }", "  prod: {}"],
      "{ delimiter: ',' }",
    );
    const files = { ...base, "flow.yaml": flow, "project.yaml": project };
    const csv = resolveAll(files, ["dev", "prod"]);
    const sql = fold(csv).files["views.sql"]!;
    expect(sql).toContain("  BULK '$(path_orders)',");
    expect(sql).toContain("  FIELDTERMINATOR = '$(delimiter_orders)'");
    expect(fold(csv).files["environments/dev.sql"]).toContain(
      ':setvar path_orders "dev/orders/*.csv"',
    );
    expect(foldFailures(csv)).toEqual([]);
  });
});
