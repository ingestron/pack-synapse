// views.sql: one re-runnable script per environment, a view per table that a
// Synapse method keeps or serves, in the model's order (inputs first).
import type { ResolvedModel, ResolvedTable, Step } from "@ingestron/definitions";
import { relativePath, sourceStep } from "./locations.js";
import { filesQuery, quote, viewStatement, type ColumnOptions } from "./sql.js";

/**
 * The pack's files: `views.sql`, or nothing when no table uses a Synapse method.
 * @example build(model)["views.sql"]
 */
export function build(model: ResolvedModel): Record<string, string> {
  const viewed = model.tables.filter(hasView);
  if (viewed.length === 0) return {};
  const several = new Set(viewed.map((table) => table.fullName.catalog)).size > 1;
  // In the model's order, so each view follows the views it reads; views are named
  // in two parts, so a USE switches database whenever the next view's differs.
  const statements: string[] = [];
  let current: string | undefined;
  for (const table of viewed) {
    if (several && table.fullName.catalog !== current) {
      current = table.fullName.catalog;
      statements.push(`USE ${quote(current)};\nGO`);
    }
    statements.push(...viewOf(model, table));
  }
  const header = [
    `-- Generated by Ingestron for ${model.project.id} (${model.project.environment}): Synapse serverless SQL views.`,
    several
      ? "-- Run against any database of the serverless pool: it switches database before each view."
      : "-- Run against the serverless database that holds the views.",
  ].join("\n");
  return { "views.sql": `${[header, ...statements].join("\n\n")}\n` };
}

/** True when the table has a Synapse view, kept or served. */
export function hasView(table: ResolvedTable): boolean {
  return table.store?.method === "synapse-view" || table.serve?.method === "synapse-serve";
}

function viewOf(model: ResolvedModel, table: ResolvedTable): string[] {
  const name = { schema: table.fullName.schema, table: table.fullName.table };
  // Resolved types are Synapse's only when Synapse provides the defaults.
  const resolvedTypes = model.standard.packs[0]?.startsWith("synapse@") ?? false;
  if (table.serve?.method === "synapse-serve")
    return [viewStatement(name, filesView(table, table.serve, { resolvedTypes }))];
  if (table.store?.method !== "synapse-view") return [];
  const renamed = table.ingest?.renamed ?? true;
  const query = table.transform
    ? transformView(model, table)
    : filesView(table, table.store, { renamed, resolvedTypes });
  return [viewStatement(name, query)];
}

/** A view over the files the table's source step records, read through the data source. */
function filesView(table: ResolvedTable, step: Step, options: ColumnOptions): string {
  const output = sourceStep(table)!.output!;
  const relative = relativePath(output, step.settings);
  // The method's check refuses this before a build; never write a wrong path.
  if ("problem" in relative) throw new Error(relative.problem);
  return filesQuery({
    ...options,
    path: relative.path,
    dataSource: String(step.settings.data_source),
    format: output.format === "csv" ? "csv" : "parquet",
    columns: table.contract.columns,
    csv: csvOf(table, step),
  });
}

/** The transform's SQL, its inputs named by their views, selecting the contract's columns. */
function transformView(model: ResolvedModel, table: ResolvedTable): string {
  const code = withoutSemicolon(table.transform!.code).replace(
    tableReference,
    (written, input: string) => {
      const found = model.tables.find((item) => item.name === input);
      if (!found) return written;
      const { catalog, schema, table: name } = found.fullName;
      // A view in another database is named in three parts.
      const database = catalog === table.fullName.catalog ? "" : `${quote(catalog)}.`;
      return `${database}${quote(schema)}.${quote(name)}`;
    },
  );
  const columns = table.contract.columns.map((column) => quote(column.name)).join(", ");
  return [`SELECT ${columns}`, "FROM (", code, ") AS [source]"].join("\n");
}

/** `{{ tables.x }}`, with or without Jinja's `-` whitespace markers. */
export const tableReference = /\{\{-?\s*tables\.([A-Za-z0-9_-]+)\s*-?\}\}/g;

/** A view's subquery cannot end with `;`. */
function withoutSemicolon(code: string): string {
  return code.trim().replace(/;\s*$/, "");
}

/**
 * How CSV files are read: the Synapse step's own `csv` when written, else the
 * landing step's, else the default.
 */
function csvOf(table: ResolvedTable, step: Step): { header: boolean; delimiter: string } {
  const own = step.settings.csv as { header: boolean; delimiter: string };
  if (step.origins.csv?.layer !== "pack") return own;
  const settings = sourceStep(table)?.settings ?? {};
  const landed = (settings.csv as Partial<typeof own> | undefined) ?? fromOptions(settings.options);
  return { ...own, ...landed };
}

/** ADF's free-form reader options: `header` (true or "true") and `sep` or `delimiter`. */
function fromOptions(options: unknown): Partial<{ header: boolean; delimiter: string }> {
  if (typeof options !== "object" || options === null) return {};
  const { header, sep, delimiter } = options as Record<string, unknown>;
  const separator = sep ?? delimiter;
  return {
    ...(header !== undefined && { header: header === true || header === "true" }),
    ...(typeof separator === "string" && { delimiter: separator }),
  };
}
