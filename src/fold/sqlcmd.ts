// The sqlcmd side of the fold: each environment's wrapper, which sets the values
// views.sql takes with :setvar and includes it with :r, and what sqlcmd makes of
// views.sql for one environment (spec sections 8.3 and 9).
import type { Variable } from "./fold-places.js";
import { checksFile, viewsFile } from "../output/index.js";

/** The wrapper's path for an environment. */
export const environmentFile = (target: string): string => `environments/${target}.sql`;

/** The checks wrapper's path for an environment. */
export const checksWrapperFile = (target: string): string => `checks/${target}.sql`;

/** A script a wrapper includes: its file, its wrapper's path, and what follows `:r`. */
export interface Script {
  file: string;
  wrapperOf: (target: string) => string;
  after: string[];
}

/** views.sql, wrapped by `environments/<target>.sql`. */
export const viewsScript: Script = { file: viewsFile, wrapperOf: environmentFile, after: [] };

/** checks.sql, wrapped by `checks/<target>.sql`; it has no `GO` of its own, so one follows. */
export const checksScript: Script = {
  file: checksFile,
  wrapperOf: checksWrapperFile,
  after: ["GO"],
};

/** A reference to a variable in views.sql. */
export const reference = (name: string): string => `$(${name})`;

/**
 * `:setvar name "value"`, with each `"` in the value doubled, as sqlcmd reads a
 * quoted value.
 */
export function setvar(name: string, value: string): string {
  return `:setvar ${name} "${value.replaceAll('"', '""')}"`;
}

/**
 * The wrapper for one environment: stop at the first error, set every variable the
 * environment sets, stop when the deploying pipeline has not supplied one it leaves,
 * then include the script, views.sql unless another is given, which sqlcmd finds from the
 * folder it starts in.
 */
export function wrapper(
  project: string,
  target: string,
  variables: readonly Variable[],
  script: Script = viewsScript,
): string {
  const left = variables.filter((variable) => !(target in variable.values));
  const header = [
    `-- Generated by Ingestron for ${project}: what ${script.file} takes in ${target}. Do not edit.`,
    `-- Run it from the folder that holds ${script.file}: sqlcmd reads :r paths from where it starts.`,
    `--   sqlcmd -S <workspace>-ondemand.sql.azuresynapse.net -i ${script.wrapperOf(target)}`,
    ...(left.length === 0 ? [] : [suppliedLine(left.map((variable) => variable.name))]),
  ];
  const sets = variables.flatMap((variable) =>
    target in variable.values ? [setvar(variable.name, variable.values[target]!)] : [],
  );
  const guards = left.map((variable) => guard(variable.name));
  const end = guards.length > 0 ? ["GO"] : [];
  return `${[...header, ":on error exit", ...sets, ...guards, ...end, `:r ${script.file}`, ...script.after].join("\n")}\n`;
}

/** Which variables the deploying pipeline supplies, and how. */
function suppliedLine(names: readonly string[]): string {
  const how =
    names.length === 1
      ? "as an environment variable of that name"
      : "as environment variables of those names";
  return `-- The deploying pipeline supplies ${names.join(", ")}, ${how}, in the same case.`;
}

/**
 * Stops the script when a variable is not set. sqlcmd (Go) leaves an unknown `$(name)`
 * in the text and runs on, so the comparison is true only then; the ODBC sqlcmd stops
 * at the unknown variable itself.
 */
function guard(name: string): string {
  return `IF N'${reference(name)}' = N'$' + N'(${name})' THROW 50000, N'${name} is not set: the deploying pipeline supplies it, as an environment variable or with sqlcmd -v.', 1;`;
}

/**
 * views.sql, and checks.sql when there is one, as sqlcmd runs them for one target: each
 * `$(name)` replaced by the value the target's wrapper sets, else by `supplied`, the text
 * standing for what the deploying pipeline supplies. A name neither gives stays as it is.
 */
export function substituted(
  files: Readonly<Record<string, string>>,
  target: string,
  supplied: Readonly<Record<string, string>>,
): Record<string, string> {
  const values = new Map(
    Object.entries(supplied).map(([name, value]) => [name.toLowerCase(), value]),
  );
  for (const [, name, value] of (files[environmentFile(target)] ?? "").matchAll(setvarLine))
    values.set(name!.toLowerCase(), value!.replaceAll('""', '"'));
  const replaced = (text: string) =>
    text.replace(
      /\$\(([A-Za-z0-9_-]+)\)/g,
      (found, name: string) => values.get(name.toLowerCase()) ?? found,
    );
  return Object.fromEntries(
    [viewsFile, checksFile].flatMap((file) =>
      files[file] === undefined ? [] : [[file, replaced(files[file])]],
    ),
  );
}

const setvarLine = /^:setvar ([A-Za-z0-9_-]+) "((?:[^"]|"")*)"$/gm;
